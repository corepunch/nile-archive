#!/usr/bin/env python3
"""Build/check the engine skin and single-texture game overrides, preserving alpha.

Default source: one authored ImageGen atlas. Only crop/rotate/resize registration
is used. Game overrides copy their existing RGBA canvases byte-for-byte; no
control states are recolored or derived. --check never writes runtime assets.
"""
import argparse
import importlib.util
import io
import json
import math
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
STATES = ['normal', 'selected', 'pressed', 'hover', 'disabled']
NAMES = ([f'kind-{i}' for i in range(8)] +
         ['ray-row', 'ray-column', 'ray-diagonal', 'bomb', 'prism', 'sand', 'chain', 'ice-2',
          'ice-1', 'selected', 'hint', 'guide', 'cell-mask', 'score', 'complete', 'moves'] +
         [f'{tool}-{state}' for tool in ['pickaxe', 'dynamite', 'sunburst', 'pause'] for state in STATES] +
         ['hud-panel', 'tool-tray', 'board-frame', 'background'] +
         [f'spark-{i}' for i in range(8)] + [f'ice-puff-{i}' for i in range(4)] + [f'impact-{i}' for i in range(4)])
HEX = {'sand', 'chain', 'ice-2', 'ice-1', 'selected', 'hint', 'cell-mask', 'board-frame'}


def lua_table(frames, path=None):
    header = '-- Generated by python3 tools/match3_atlas.py; do not edit.\nreturn {\n'
    if path:
        header += f'    path="{path}",\n    frames={{\n'
    indent = '        ' if path else '    '
    for name, box in frames.items():
        header += indent + f'["{name}"]={{' + ','.join(map(str, box)) + '},\n'
    return header + ('    },\n' if path else '') + '}\n'


def write_or_check(path, value, check):
    if isinstance(value, str):
        value = value.encode()
    if check:
        current = path.read_bytes() if path.exists() else None
        if current is not None and path.suffix == '.png':
            # Compression bytes can vary between Pillow/zlib versions. The
            # authored RGBA pixels and registration are the runtime contract.
            actual, expected = Image.open(io.BytesIO(current)), Image.open(io.BytesIO(value))
            matches = actual.mode == expected.mode and actual.size == expected.size and actual.tobytes() == expected.tobytes()
        else:
            matches = current == value
        assert matches, f'Stale {path.relative_to(ROOT)}: run python3 tools/match3_atlas.py'
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(value)


def png(image):
    result = io.BytesIO()
    image.save(result, format='PNG', optimize=True)
    return result.getvalue()


def build_default(check):
    source = Image.open(ROOT / 'engine/art/match3/source.png').convert('RGBA')
    brick = Image.open(ROOT / 'engine/art/match3/source-brick.png').convert('RGBA')
    rows = [0, 167, 338, 499, 644, 795, 947, 1103, 1254]
    assert source.size == (1254, 1254)
    image = Image.new('RGBA', (1024, 1024))
    frames, registration = {}, {}
    for i, name in enumerate(NAMES):
        row, col = divmod(i, 8)
        box = [round(col * source.width / 8), rows[row], round((col + 1) * source.width / 8), rows[row + 1]]
        sprite = source.crop(box)
        if name == 'kind-1':
            box = [156, 36, 315, 163]
            sprite = brick.crop(box)
        angle = 30 if name in HEX else 0
        if angle:
            sprite = sprite.rotate(angle, Image.Resampling.BICUBIC, expand=True)
        sprite.thumbnail((124, 124), Image.Resampling.LANCZOS)
        x, y = col * 128, row * 128
        image.paste(sprite, (x + (128 - sprite.width) // 2, y + (128 - sprite.height) // 2))
        frames[name] = [x, y, 128, 128]
        registration[name] = {'crop': box, 'rotation': angle, 'size': list(sprite.size), 'runtime': frames[name]}
        if name == 'kind-1':
            registration[name]['source'] = 'engine/art/match3/source-brick.png'
            registration[name]['prompt'] = 'engine/art/match3/brick.prompt.txt'
    frames["glow"] = frames["spark-0"]
    raw = png(image)
    write_or_check(ROOT / 'engine/data/match3.png', raw, check)
    write_or_check(ROOT / 'engine/match3_frames.lua', lua_table(frames), check)
    manifest = {'generator': 'built-in image_gen; one atlas, all icon/control states together',
                'source': 'engine/art/match3/source.png', 'prompt': 'engine/art/match3/prompt.txt',
                'kinds': ['gold', 'brick', 'timber', 'grain', 'stone', 'water', 'apple', 'fish'],
                'reference': 'https://www.gamehouse.com/blog/2016/04/cradle-of-rome-walkthrough/',
                'runtime': 'engine/data/match3.png', 'registration': registration,
                'reproduction': 'python3 tools/match3_atlas.py', 'review': 'docs/review/match3/README.md'}
    write_or_check(ROOT / 'engine/art/match3/manifest.json', json.dumps(manifest, indent=2) + '\n', check)
    return raw


def build_game(game, check):
    root = ROOT / 'games' / game
    if game == 'relic-rush':
        spec = importlib.util.spec_from_file_location('relic_assets', root / 'tools/prepare_assets.py')
        assets = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(assets)
        # Keep Relic Rush's original flame, independently of the engine default.
        write_or_check(root / 'data/tile-sets/relics/1.png', png(assets.original_tile(0, 1)), check)
        for (pack, kind), image in assets.hex_replacements().items():
            write_or_check(root / f'data/tile-sets/{pack}/{kind}.png', png(image), check)
    sources = {}
    packs = ['relics', 'jewels', 'resources'] if game == 'relic-rush' else ['festive']
    for pack in packs:
        for i in range(6):
            sources[f'{pack}-{i}'] = root / f'data/tile-sets/{pack}/{i}.png'
    for source in sorted((root / 'data/board-states').glob('*.png')):
        sources[source.stem] = source
    for source in sorted((root / 'data/expedition-hud').glob('*.png')):
        sources[source.stem] = source
    if game == 'relic-rush':
        for name, source in [('background', 'jungle.jpg'), ('scene-1', 'scene-lagoon.jpg'), ('scene-2', 'scene-temple.jpg')]:
            sources[name] = root / 'data' / source
    else:
        sources['background'] = root / 'data/winter.jpg'
        sources['character'] = root / 'data/characters/noelle.png'
    loaded = {name: Image.open(path).convert('RGBA') for name, path in sources.items()}
    glow = Image.new("RGBA", (64, 64))
    glow.putdata([(255, 255, 255, math.floor(255 * max(0, 1 - math.hypot(x - 31.5, y - 31.5) / 32) ** 3))
                  for y in range(64) for x in range(64)])
    loaded["glow"] = glow
    width, x, y, row_h, frames = 2048, 2, 2, 0, {}
    order = sorted(loaded, key=lambda key: (-loaded[key].height, key))
    for name in order:
        sprite = loaded[name]
        if x + sprite.width + 2 > width:
            x, y, row_h = 2, y + row_h + 4, 0
        frames[name] = [x, y, sprite.width, sprite.height]
        x, row_h = x + sprite.width + 4, max(row_h, sprite.height)
    height = 1 << (y + row_h + 3).bit_length()
    image = Image.new('RGBA', (width, height))
    for name in order:
        image.paste(loaded[name], tuple(frames[name][:2]))
    # Canonical names plus optional packs all borrow the same GPU allocation.
    for i in range(6):
        frames[f'kind-{i}'] = frames[f'{packs[0]}-{i}']
    if game == 'christmas-market':
        frames['scene-1'] = frames['scene-2'] = frames['background']
        frames['score'] = frames['complete']
    write_or_check(root / 'data/match3.png', png(image), check)
    write_or_check(root / 'lua/match3_skin.lua', lua_table(frames, 'match3.png'), check)
    manifest = {'runtime': 'data/match3.png', 'size': [width, height], 'frames': frames,
                'sources': {name: str(path.relative_to(root)) for name, path in sources.items()},
                'procedural_glow': 'Original 64px white cubic radial alpha; transient light, packed alongside sprites',
                'transform': 'RGBA canvases packed without resizing, recoloring or alpha changes; 2px transparent gutters',
                'reproduction': 'python3 tools/match3_atlas.py', 'review': 'docs/review/trickling/README.md'}
    write_or_check(root / 'art/match3-atlas.json', json.dumps(manifest, indent=2) + '\n', check)
    # Compare each packed canvas with its source, including RGB beneath alpha.
    for name, original in loaded.items():
        xx, yy, ww, hh = frames[name]
        assert image.crop((xx, yy, xx + ww, yy + hh)).tobytes() == original.tobytes(), name
    print(f'{game}: {len(sources)} images in one {width}x{height} atlas')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    build_default(args.check)
    for game in ['relic-rush', 'christmas-market']:
        build_game(game, args.check)


if __name__ == '__main__':
    main()

"""Pack a game's retained CC0 Kenney particle sprites into one additive atlas (needs Pillow).

    python3 tools/pack_particles.py relic-rush|christmas-market [--check]

The sources in games/<game>/art/particles/kenney/ are Kenney's black-background greyscale
PNGs. Each becomes white with its brightness as alpha, so additive drawing and a
per-kind tint reproduce the original glow. Only resizing is applied.
"""
from pathlib import Path
import sys

from PIL import Image

ROOT = Path(__file__).resolve().parents[1] / 'games' / sys.argv[1]
SOURCE, ATLAS, SKIN = ROOT / 'art/particles/kenney', ROOT / 'data/particles.png', ROOT / 'lua/particle_skin.lua'
GUTTER = 2
# runtime name: (Kenney file, packed size)
SPRITES = {
    'shock': ('circle_03', 256),    # bomb double shockwave
    'flash': ('light_01', 256),     # bomb bloom
    'burst': ('star_09', 256),      # bomb centre flare
    'ring': ('circle_02', 128),     # impact ring
    'glint': ('star_07', 128),      # impact and blast twinkle
    'twinkle': ('star_06', 128),    # spark particles
    'streak': ('trace_06', 128),    # shard particles, long axis vertical
}


def sprite(name, size):
    grey = Image.open(SOURCE / f'{name}.png').convert('L').resize((size, size), Image.Resampling.LANCZOS)
    out = Image.new('RGBA', grey.size, (255, 255, 255, 0))
    out.putalpha(grey)
    return out


def build():
    big = [k for k, (_, s) in SPRITES.items() if s == 256]
    small = [k for k, (_, s) in SPRITES.items() if s == 128]
    cell_big, cell_small = 256 + 2 * GUTTER, 128 + 2 * GUTTER
    width = len(big) * cell_big + ((len(small) + 1) // 2) * cell_small
    atlas = Image.new('RGBA', (width, max(cell_big, 2 * cell_small)), (255, 255, 255, 0))
    frames = {}
    for i, key in enumerate(big):
        x, y = i * cell_big + GUTTER, GUTTER
        atlas.paste(sprite(*SPRITES[key]), (x, y))
        frames[key] = (x, y, 256, 256)
    for i, key in enumerate(small):
        x, y = len(big) * cell_big + (i // 2) * cell_small + GUTTER, (i % 2) * cell_small + GUTTER
        atlas.paste(sprite(*SPRITES[key]), (x, y))
        frames[key] = (x, y, 128, 128)
    lines = [f'-- Generated by python3 tools/pack_particles.py {sys.argv[1]}; do not edit.',
             '-- CC0 Particle Pack by Kenney (art/particles/kenney/License.txt).', 'return {',
             '    path="particles.png",', '    frames={']
    lines += [f'        ["{k}"]={{{x},{y},{w},{h}}},' for k, (x, y, w, h) in frames.items()]
    lines += ['    },', '}', '']
    return atlas, '\n'.join(lines)


def main():
    atlas, skin = build()
    if '--check' in sys.argv:
        stale = not SKIN.exists() or SKIN.read_text() != skin or not ATLAS.exists() \
            or Image.open(ATLAS).convert('RGBA').tobytes() != atlas.tobytes()
        if stale:
            sys.exit(f'Stale particle atlas: run python3 tools/pack_particles.py {sys.argv[1]}')
        return
    atlas.save(ATLAS, optimize=True)
    SKIN.write_text(skin)
    print(f'{len(SPRITES)} particle sprites in one {atlas.width}x{atlas.height} atlas')


if __name__ == '__main__':
    main()

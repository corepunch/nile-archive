#!/usr/bin/env python3
"""Fit every authored board's move budget to its tier.

Boards are authored in games/<game>/lua/campaign.lua (docs/LEVEL_DESIGN.md);
only the budget is fitted. The greedy bot (tests/lua/tune_moves.lua) plays each board
on hashed seeds, with its earned buildings and a 250-move ceiling. The budget
uses the tier's median margin and leaves enough room for slower starts.
Writes each board's `moves` into games/<game>/lua/campaign.lua and a review
table in games/<game>/docs/level-moves.md. Chunks of levels run in parallel.

    make build/test/relic-rush
    python3 tools/tune_moves.py relic-rush                 # every level
    python3 tools/tune_moves.py christmas-market --levels 1-20 --seeds 60
"""
import argparse
import concurrent.futures
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import time

from square_boards import parse

ROOT = Path(__file__).resolve().parents[1]


def run(game, first, last, seeds):
    # Each process logs to build/test/<game>.log under its own working
    # directory, so parallel chunks run in a scratch tree of links.
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for name in ('engine', 'games', 'tests', 'art', 'docs', 'tools'):
            if (ROOT / name).exists():
                (tmp / name).symlink_to(ROOT / name)
        (tmp / 'build/test').mkdir(parents=True)
        env = {**os.environ, 'TUNE_LEVELS': f'{first}-{last}', 'BALANCE_RUNS': str(seeds),
               'SPRITE_SAVE_DIR': str(tmp / 'save')}
        proc = subprocess.run([str(ROOT / f'build/test/{game}'), '--headless', '--mute', 'rules tune_moves'],
                       cwd=tmp, env=env, capture_output=True, text=True)
        log = (tmp / f'build/test/{game}.log').read_text()
    rows = [json.loads(line.split('MOVES_JSON ', 1)[1]) for line in log.splitlines() if 'MOVES_JSON ' in line]
    if proc.returncode or len(rows) != last - first + 1:
        raise RuntimeError(f'{game} levels {first}–{last} failed to fit (exit {proc.returncode}):\n{log[-3000:]}')
    return rows


def levels(spec, count):
    for span in (spec or f'1-{count}').split(','):
        first, _, last = span.partition('-')
        yield int(first), int(last or first)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('game')
    parser.add_argument('--levels', help='A-B or a comma-separated list, one-based and inclusive (default: all)')
    parser.add_argument('--seeds', type=int, default=40)
    parser.add_argument('--chunk', type=int, default=12, help='boards per sampling process')
    args = parser.parse_args()
    game = ROOT / 'games' / args.game
    campaign = game / 'lua/campaign.lua'
    boards = parse(campaign.read_text())
    count = len(boards)
    started = time.time()
    chunks = [(a, min(last, a + args.chunk - 1)) for first, last in levels(args.levels, count)
              for a in range(first, last + 1, args.chunk)]
    with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 4) as pool:
        rows = [r for part in pool.map(lambda c: run(args.game, c[0], c[1], args.seeds), chunks) for r in part]

    path = game / 'docs/level-moves.json'
    merged = {r['level']: r for r in json.loads(path.read_text())} if path.exists() else {}
    merged.update({r['level']: r for r in rows})
    rows = [merged[k] for k in sorted(merged)]
    path.write_text(json.dumps(rows, indent=1, sort_keys=True) + '\n')

    # Each board table starts `{name="…", tier="…",`; its budget follows the tier.
    budget = {r['level']: r['moves'] for r in rows}
    seen = [0]

    def fit(m):
        seen[0] += 1
        moves = budget.get(seen[0])
        return m.group(1) + (f' moves={moves},' if moves else m.group(2) or '')
    text = re.sub(r'(\{name="[^"]+", tier="\w+",)( moves=\d+,)?', fit, campaign.read_text())
    campaign.write_text(text)
    names = {n: b['name'] for n, b in enumerate(boards, 1)}
    md = ['# Move budgets', '',
          'Generated by `python3 tools/tune_moves.py ' + args.game + '` from `lua/campaign.lua`. The greedy bot (best evaluated swap,',
          'no tools) plays each authored board on hashed seeds with its earned buildings and a 250-move ceiling.',
          'The budget starts at the median clear times the tier margin (tutorial 2.5, easy 2, normal 1.4,',
          'hard 1.2, boss 1). When needed it grows to fit 90%, 80%, 75%, 70%, or 65% of samples',
          'respectively. "Within budget" measures this bot sample. Human win rates may differ.', '',
          '| # | Board | Tier | Moves | Median | Fastest | Within budget |', '| ---: | --- | --- | ---: | ---: | ---: | ---: |']
    md += [f"| {r['level']} | {names.get(r['level'], '')} | {r['tier']} | {r['moves']} | {r['median']} | "
           f"{r['fastest']} | {r.get('within', r['wins'])}/{r['seeds']} |" for r in rows]
    (game / 'docs/level-moves.md').write_text('\n'.join(md) + '\n')
    for r in rows:
        if r['median'] < 0:
            print(f"board {r['level']}: the bot cannot clear it in half its games; redesign it")
    print(f'{len(chunks)} chunks, {time.time() - started:.0f} s; wrote lua/campaign.lua and docs/level-moves.md')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Fit every authored board's move budget to its tier.

Boards are authored in games/<game>/levels (docs/LEVEL_DESIGN.md); only the
budget is fitted. The greedy bot (tests/lua/tune_moves.lua) plays each board
on hashed seeds with no move limit, and the budget is the moves it needed in
the tier's target share of games: tutorial 95%, easy 92%, normal 80%, hard
62%, boss 50%. Writes games/<game>/lua/level_moves.lua and a review table in
games/<game>/docs/level-moves.md. Chunks of levels run in parallel.

    make build/test/relic-rush
    python3 tools/tune_moves.py relic-rush                 # every level
    python3 tools/tune_moves.py christmas-market --levels 1-20 --seeds 60
"""
import argparse
import concurrent.futures
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]


def run(game, first, last, seeds):
    # Each process logs to build/test/<game>.log under its own working
    # directory, so parallel chunks run in a scratch tree of links.
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        for name in ('engine', 'games', 'tests', 'art', 'docs', 'tools'):
            if (ROOT / name).exists():
                (tmp / name).symlink_to(ROOT / name)
        (tmp / 'build/test').mkdir(parents=True)
        env = {**os.environ, 'TUNE_LEVELS': f'{first}-{last}', 'BALANCE_RUNS': str(seeds),
               'SPRITE_SAVE_DIR': str(tmp / 'save')}
        subprocess.run([str(ROOT / f'build/test/{game}'), '--headless', '--mute', 'rules tune_moves'],
                       cwd=tmp, env=env, capture_output=True, text=True)
        log = (tmp / f'build/test/{game}.log').read_text()
    rows = [json.loads(line.split('MOVES_JSON ', 1)[1]) for line in log.splitlines() if 'MOVES_JSON ' in line]
    assert len(rows) == last - first + 1, log[-3000:]
    return rows


def levels(spec, count):
    first, last = (int(v) for v in spec.split('-')) if spec else (1, count)
    return first, last


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('game')
    parser.add_argument('--levels', help='A-B, one-based and inclusive (default: all)')
    parser.add_argument('--seeds', type=int, default=40)
    parser.add_argument('--chunk', type=int, default=5)
    args = parser.parse_args()
    game = ROOT / 'games' / args.game
    count = len(list((game / 'levels').glob('level_*.txt')))
    first, last = levels(args.levels, count)
    started = time.time()
    chunks = [(a, min(last, a + args.chunk - 1)) for a in range(first, last + 1, args.chunk)]
    with concurrent.futures.ThreadPoolExecutor(os.cpu_count() or 4) as pool:
        rows = [r for part in pool.map(lambda c: run(args.game, c[0], c[1], args.seeds), chunks) for r in part]

    path = game / 'docs/level-moves.json'
    merged = {r['level']: r for r in json.loads(path.read_text())} if path.exists() else {}
    merged.update({r['level']: r for r in rows})
    rows = [merged[k] for k in sorted(merged)]
    path.write_text(json.dumps(rows, indent=1, sort_keys=True) + '\n')

    lua = ['-- Generated by tools/tune_moves.py from the bot\'s plays of lua/boards.lua.',
           '-- Do not edit by hand; rerun the tuner after changing a board.', 'return {']
    lua += [f"    [{r['level']}] = {r['moves']},   -- {r['tier']}" for r in rows]
    (game / 'lua/level_moves.lua').write_text('\n'.join(lua + ['}']) + '\n')

    names = {}
    for f in (game / 'levels').glob('level_*.txt'):
        m = re.search(r'^name:\s*(.+)$', f.read_text(), re.M)
        names[int(f.stem[6:])] = m.group(1) if m else ''
    md = ['# Move budgets', '',
          'Generated by `python3 tools/tune_moves.py ' + args.game + '`. The greedy bot (best evaluated swap,',
          'no tools) clears each authored board on hashed seeds with no move limit. The budget is the',
          'moves it needed in the tier\'s share of games (tutorial 95%, easy 92%, normal 80%, hard 62%,',
          'boss 50%). The bot orders and spaces the boards; its rates are not human win rates.', '',
          '| # | Board | Tier | Moves | Median | Fastest | Bot clears |', '| ---: | --- | --- | ---: | ---: | ---: | ---: |']
    md += [f"| {r['level']} | {names.get(r['level'], '')} | {r['tier']} | {r['moves']} | {r['median']} | "
           f"{r['fastest']} | {r['wins']}/{r['seeds']} |" for r in rows]
    (game / 'docs/level-moves.md').write_text('\n'.join(md) + '\n')
    print(f'{len(chunks)} chunks, {time.time() - started:.0f} s; wrote lua/level_moves.lua and docs/level-moves.md')


if __name__ == '__main__':
    main()

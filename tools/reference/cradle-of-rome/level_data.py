#!/usr/bin/env python3
"""Export every Cradle of Rome level as design data: per-level features,
feature first appearances and ASCII maps, for authoring our own hex levels.

    python3 tools/reference/cradle-of-rome/level_data.py
    python3 tools/reference/cradle-of-rome/level_data.py --check

Writes docs/cradle-of-rome-reference/levels.json (every level, every field)
and docs/cradle-of-rome-reference/LEVELS.md (the progression tables). The
level files come from the local extraction in reference/cradle-of-rome; see
its SOURCE.txt. --check fails if either output is stale.
"""
import argparse
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyze  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
LEVELS = ROOT / 'reference/cradle-of-rome/resources/settings/scenes/game/levels'
OUT = ROOT / 'docs/cradle-of-rome-reference'
RANGES = (('adventure', 1, 100), ('extras', 101, 115))
# Map legend: one character per square cell, gravity runs down the page.
LEGEND = {
    'outside': ' ', 'plain': '.', 'plaque': 'p', 'double_plaque': 'P',
    'lock': 'c', 'double_lock': 'C', 'lock_on_plaque': 'k', 'double_lock_on_plaque': 'K',
    'frozen': 'i', 'disabled': '#',
}


def cell_symbol(plaque, ball):
    if ball.get('disable') == '1':
        return LEGEND['disabled']
    if ball.get('freeze') == '1':
        return LEGEND['frozen']
    lock = ball.get('lock')
    if lock == '2':
        return LEGEND['double_lock_on_plaque' if plaque else 'double_lock']
    if lock == '1':
        return LEGEND['lock_on_plaque' if plaque else 'lock']
    return {0: LEGEND['plain'], 1: LEGEND['plaque'], 2: LEGEND['double_plaque']}[plaque]


def fed(cells, blocked):
    """Cells a straight-down fall can supply from the top cell of each column
    (the source boards mark their supply points on the top row)."""
    reach = set()
    for (x, y) in sorted(cells, key=lambda c: c[1]):
        if (x, y) in blocked:
            continue
        if (x, y - 1) not in cells or (x, y - 1) in reach:
            reach.add((x, y))
    return reach


def symmetric(cells, key):
    xs = [x for x, _ in cells]
    axis = min(xs) + max(xs)
    return all(((axis - x, y) in cells and key(cells[axis - x, y]) == key(cells[x, y])) for x, y in cells)


def level(n):
    board, cells = analyze.read_board(LEVELS / f'level_{n}.xml')
    locks = {c for c, (_, ball) in cells.items() if ball.get('lock') or ball.get('freeze') == '1'}
    open_reach = fed(cells, set())
    gated = sorted(c for c in open_reach - fed(cells, locks) if c not in locks)
    xs, ys = [x for x, _ in cells], [y for _, y in cells]
    rows = []
    for y in range(min(ys), max(ys) + 1):
        rows.append(''.join(cell_symbol(*cells[x, y]) if (x, y) in cells else ' '
                            for x in range(min(xs), max(xs) + 1)).rstrip())
    s = board['settings']
    return {
        'level': n,
        'range': next(name for name, a, b in RANGES if a <= n <= b),
        'time': s.get('play_time'),
        'piece_types': s.get('allow_ball_types'),
        'puzzle_ball_probability': s.get('puzzle_ball_probability', 0),
        'width': max(xs) - min(xs) + 1, 'height': max(ys) - min(ys) + 1,
        'active': board['active'],
        'plaques': board['plaques'], 'double_plaques': board['double_plaques'],
        'single_locks': board['single_locks'], 'double_locks': board['double_locks'],
        'locked_plaques': board['locked_plaques'],
        'frozen': board['frozen'], 'disabled': board['disabled'],
        'generators': board['generators'],
        'groups': [list(g) for g in board['components']],
        'mirror_shape': symmetric(cells, lambda _: True),
        'mirror_layout': symmetric(cells, lambda c: cell_symbol(*c)),
        'gated_cells': len(gated),
        'map': rows,
    }


FEATURES = (
    ('plaque', lambda r: r['plaques'] > 0, 'Single plaque (blue tablet)'),
    ('lock', lambda r: r['single_locks'] > 0, 'Single chain'),
    ('lock_on_plaque', lambda r: r['locked_plaques'] > 0, 'Chain over a plaque'),
    ('gate', lambda r: r['gated_cells'] > 0, 'Chain gating cells below it'),
    ('two_groups', lambda r: len(r['groups']) > 1, 'Two or more separate areas'),
    ('double_plaque', lambda r: r['double_plaques'] > 0, 'Double plaque (green tablet)'),
    ('double_lock', lambda r: r['double_locks'] > 0, 'Double chain'),
    ('frozen', lambda r: r['frozen'] > 0, 'Ice (freeze)'),
    ('disabled', lambda r: r['disabled'] > 0, 'Disabled cell'),
    ('puzzle_balls', lambda r: r['puzzle_ball_probability'] > 0, 'Puzzle balls'),
)


def markdown(rows):
    adventure = [r for r in rows if r['range'] == 'adventure']
    out = ['# Cradle of Rome levels, as design data', '',
           'Generated by `python3 tools/reference/cradle-of-rome/level_data.py` from the local',
           'extraction (`reference/cradle-of-rome`, see its `SOURCE.txt`). Every field for every level,',
           'including ASCII maps, is in [levels.json](levels.json). Gravity runs down the page.',
           'A cell is *gated* when a straight fall from the top of its column reaches it only',
           'once the chains or ice above it break.', '',
           '## First appearance of each feature', '',
           '| Feature | Adventure level | Adventure boards with it | Extras level |', '| --- | ---: | ---: | ---: |']
    for key, has, label in FEATURES:
        first_a = next((r['level'] for r in adventure if has(r)), None)
        first_e = next((r['level'] for r in rows if r['range'] == 'extras' and has(r)), None)
        count = sum(1 for r in adventure if has(r))
        out.append(f"| {label} | {first_a or '—'} | {count} | {first_e or '—'} |")
    out += ['', 'Ice and disabled cells never appear in the 100 Adventure levels.', '',
            '## Every level', '',
            '| # | Time s | Cells | Size | Plaques (double) | Chains single / double | Chains on plaques | Gated | Areas | Mirror shape / layout |',
            '| ---: | ---: | ---: | --- | --- | --- | ---: | ---: | ---: | --- |']
    for r in rows:
        out.append(f"| {r['level']} | {r['time']} | {r['active']} | {r['width']}×{r['height']} | "
                   f"{r['plaques']} ({r['double_plaques']}) | {r['single_locks']} / {r['double_locks']} | "
                   f"{r['locked_plaques']} | {r['gated_cells']} | {len(r['groups'])} | "
                   f"{'yes' if r['mirror_shape'] else 'no'} / {'yes' if r['mirror_layout'] else 'no'} |")
    out += ['', '## Map legend', '', '| Symbol | Cell |', '| --- | --- |']
    for name, symbol in LEGEND.items():
        out.append(f"| `{symbol if symbol != ' ' else '(space)'}` | {name.replace('_', ' ')} |")
    out += ['', '## Sample maps', '']
    for n in (1, 5, 6, 10, 20, 31, 35, 40, 51, 80, 100):
        r = rows[n - 1]
        out += [f"Level {n}: {r['active']} cells, {r['plaques']} plaques ({r['double_plaques']} double), "
                f"{r['single_locks']} single and {r['double_locks']} double chains, {r['gated_cells']} gated.", '',
                '```text', *r['map'], '```', '']
    return '\n'.join(out).rstrip() + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = [level(n) for n in range(1, 116)]
    outputs = {OUT / 'levels.json': json.dumps(rows, indent=1) + '\n', OUT / 'LEVELS.md': markdown(rows)}
    for path, text in outputs.items():
        if args.check:
            assert path.read_text() == text, f'Stale {path.relative_to(ROOT)}: run {Path(__file__).relative_to(ROOT)}'
        else:
            path.write_text(text)
    print(f'{len(rows)} levels exported')


if __name__ == '__main__':
    main()

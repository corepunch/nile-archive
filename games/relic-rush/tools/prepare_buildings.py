"""Relic Rush's catalogue around its rendered sprites. Runs after tools/buildings.py.

catalogue.json and story.json own names, prices, unlocks and descriptions (a
catalogue row may end with flags, {"road": true}: a road leads to it); the
Blender registry owns the art. This writes lua/buildings.lua (which merges the
generated lua/building_sprites.lua by key), the manifest and the runtime inventory.
"""
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'art/building-catalogue'


def register_paint(paint, art):
    # Fit the three visible foundation corners before sampling the unchanged
    # registered canvas. The Blender shadow, pivot and footprint come from art.
    (x0, y0), (x1, y1), (x2, y2) = paint['to']
    xx, xy, yx, yy = x1 - x0, x2 - x0, y1 - y0, y2 - y0
    det = xx * yy - xy * yx
    transform = []
    for start, middle, end in zip(*paint['from']):
        a = ((middle - start) * yy - (end - start) * yx) / det
        b = (xx * (end - start) - xy * (middle - start)) / det
        transform.extend((a, b, start - a * x0 - b * y0))
    with Image.open(ROOT / paint['geometry']) as target:
        assert target.size == tuple(art['image']), 'The paint-over needs a matching geometry render'
    with Image.open(ROOT / paint['source']) as image:
        image.convert('RGBA').transform(tuple(art['image']), Image.Transform.AFFINE, transform,
                                        Image.Resampling.BICUBIC).save(ROOT / art['sprite'], optimize=True)


def main():
    registry = json.loads((ART / 'registration.json').read_text())
    catalogue = json.loads((ART / 'catalogue.json').read_text())
    stories = json.loads((ART / 'story.json').read_text())
    entries = []
    lua = ['-- Generated by tools/prepare_buildings.py; do not edit.',
           'local sprites = require("building_sprites")', 'local items = {']
    for i, (key, name, category, w, h, gold, stars, reference, *flags) in enumerate(catalogue):
        road = bool(flags and flags[0].get('road'))   # a decoration on a foundation: a road leads to it
        art = registry['items'][key]
        assert art['size'] == [w, h], key
        story = stories.get(key, {})
        cost = story.get('cost', [gold, 0, 0])
        about = story.get('about', 'Place this treasure anywhere on open grass.')
        entries.append(dict(id=i, key=key, name=name, category=category, size=[w, h], pivot=art['pivot'],
            base_width=art['base_width'], gold=cost[0], stars=stars, runtime=art['sprite'], image=art['image'],
            source=registry['master'], reference=reference, cost=cost, about=about, road=road,
            shadow=dict(runtime=art['shadow'], source=registry['master'], pivot=art['shadow_pivot'],
                        base_width=art['shadow_base_width'])))
        site = story.get('fixed_site')
        if site:
            entries[-1]['fixed_site'] = site
        if 'paint' in story:
            register_paint(story['paint'], art)
            entries[-1]['paint'] = story['paint']
        lua.append('    {key=%s, %sname=%s, category=%s, cleared=%d, about=%s, cost=purse(%d,%d,%d), needs=purse(0,0,0,%d)%s},' % (
            json.dumps(key), 'road=true, ' if road else '', json.dumps(name), json.dumps(category), stars // 3, json.dumps(about), *cost, stars // 3,
            ', fixed_site=vec2(%d,%d)' % tuple(site) if site else ''))
    lua += ['}', 'for _, b in ipairs(items) do', '    for field, value in pairs(sprites[b.key]) do b[field] = value end', 'end', 'return items']
    (ROOT / 'lua/buildings.lua').write_text('\n'.join(lua) + '\n')
    (ART / 'manifest.json').write_text(json.dumps(dict(source=registry['master'], generator=registry['scene_generator'],
        registration='art/building-catalogue/registration.json', camera=registry['camera'],
        paintover=registry.get('paintover'), items=entries), indent=2) + '\n')
    inventory = ROOT / 'art/board-states/manifest.json'
    board = json.loads(inventory.read_text())
    board['runtime_inventory'] = sorted(str(p.relative_to(ROOT)) for p in (ROOT / 'data').rglob('*') if p.is_file())
    inventory.write_text(json.dumps(board, indent=2) + '\n')
    print(f'Relic Rush catalogue: {len(entries)} buildings')


if __name__ == '__main__':
    main()

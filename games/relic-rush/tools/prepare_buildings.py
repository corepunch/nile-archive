"""Relic Rush's catalogue around its rendered sprites. Runs after tools/buildings.py.

catalogue.json and story.json own names, prices, unlocks and descriptions; the
Blender registry owns the art. This writes lua/buildings.lua (which merges the
generated lua/building_sprites.lua by key), the manifest and the runtime inventory.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'art/building-catalogue'


def main():
    registry = json.loads((ART / 'registration.json').read_text())
    catalogue = json.loads((ART / 'catalogue.json').read_text())
    stories = json.loads((ART / 'story.json').read_text())
    assert len(catalogue) == 96
    entries = []
    lua = ['-- Generated by tools/prepare_buildings.py; do not edit.',
           'local sprites = require("building_sprites")', 'local items = {']
    for i, (key, name, category, w, h, gold, stars, reference) in enumerate(catalogue):
        art = registry['items'][key]
        assert art['size'] == [w, h], key
        story = stories.get(key, {})
        cost = story.get('cost', [gold, 0, 0])
        about = story.get('about', 'Place this treasure anywhere on open grass.')
        entries.append(dict(id=i, key=key, name=name, category=category, size=[w, h], pivot=art['pivot'],
            base_width=art['base_width'], gold=gold, stars=stars, runtime=art['sprite'], image=art['image'],
            source=registry['master'], reference=reference, cost=cost, about=about,
            shadow=dict(runtime=art['shadow'], source=registry['master'], pivot=art['shadow_pivot'],
                        base_width=art['shadow_base_width'])))
        lua.append('    {key=%s, name=%s, category=%s, stars=%d, about=%s, cost=purse(%d,%d,%d), needs=purse(0,0,0,%d)},' % (
            json.dumps(key), json.dumps(name), json.dumps(category), stars, json.dumps(about), *cost, stars))
    lua += ['}', 'for _, b in ipairs(items) do', '    for field, value in pairs(sprites[b.key]) do b[field] = value end', 'end', 'return items']
    (ROOT / 'lua/buildings.lua').write_text('\n'.join(lua) + '\n')
    (ART / 'manifest.json').write_text(json.dumps(dict(source=registry['master'], generator=registry['scene_generator'],
        registration='art/building-catalogue/registration.json', camera=registry['camera'],
        paintover=registry.get('paintover'), items=entries), indent=2) + '\n')
    inventory = ROOT / 'art/board-states/manifest.json'
    board = json.loads(inventory.read_text())
    board['runtime_inventory'] = sorted(str(p.relative_to(ROOT)) for p in (ROOT / 'data').rglob('*') if p.is_file())
    inventory.write_text(json.dumps(board, indent=2) + '\n')
    print(f'Relic Rush catalogue: {len(entries)} buildings')


if __name__ == '__main__':
    main()

"""Crop the single authored RGBA atlas and emit registered runtime definitions.

Only spatial crop/resize registration is applied; authored alpha is untouched.
"""
import json
from pathlib import Path
from PIL import Image
from prepare_assets import isolate_sprite

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'art/building-catalogue'


def main():
    registration = json.loads((ART/'registration.json').read_text())
    source = Image.open(ART/'paintover-atlas.png')
    assert source.mode == 'RGBA', 'Paint-over must have authored transparency'
    assert source.getchannel('A').getextrema()[0] == 0
    sx, sy = source.width/registration['size'][0], source.height/registration['size'][1]
    assert abs(sx/sy-1) < .01, 'Atlas aspect ratio changed'
    catalogue = json.loads((ART/'catalogue.json').read_text())
    sheets = json.loads((ART/'sheets.json').read_text())
    source_images = {name:Image.open(ART/name) for name in {v['source'] for v in sheets.values()}}
    stories = json.loads((ART/'story.json').read_text())
    measurements = json.loads((ART/'measurements.json').read_text()) if (ART/'measurements.json').exists() else {}
    entries, lua = [], ['-- Generated by tools/prepare_buildings.py; do not edit.','return {']
    assert len(catalogue) == len(registration['items']) == 96
    for i, (row, reg) in enumerate(zip(catalogue,registration['items'])):
        key, name, category, w, h, gold, stars, reference = row
        assert key == reg['key']
        box = [round(v*(sx if j%2==0 else sy)) for j,v in enumerate(reg['box'])]
        authored_source='paintover-atlas.png'
        if str(i) in sheets:
            selection=sheets[str(i)]
            authored_source=selection['source']
            box=selection['box']
            sprite,crop=isolate_sprite(source_images[authored_source].crop(box),with_box=True)
        else:
            sprite = source.crop(box)
            # Crop empty margins, keeping every authored leaf and alpha edge.
            crop = sprite.getchannel('A').getbbox()
            assert crop, key
            sprite = sprite.crop(crop)
        path = f'data/buildings/{i}.png' if i < 10 else f'data/buildings/{key}.png'
        sprite.save(ROOT/path,optimize=True)
        pivot = [round(reg['pivot'][0]*sx-box[0]-crop[0],3),round(reg['pivot'][1]*sy-box[1]-crop[1],3)]
        entry = dict(id=i,key=key,name=name,category=category,size=[w,h],pivot=pivot,
            base_width=round(reg['base_width']*sx,3),gold=gold,stars=stars,
            runtime=path,source='art/building-catalogue/'+authored_source,
            box=box,crop=list(crop),reference=reference)
        if key in measurements:
            entry.update(pivot=measurements[key]['pivot'],base_width=measurements[key]['base_width'])
            pivot=entry['pivot']
        entries.append(entry)
        entry['cost']=stories[key]['cost'] if key in stories else [gold,0,0]
        entry['about']=stories[key]['about'] if key in stories else 'Place this treasure anywhere on open grass.'
        lua.append('    {key=%s, name=%s, category=%s, stars=%d, about=%s, sprite_path=%s, size=size2(%d,%d), pivot=vec2(%g,%g), base_width=%g, cost=purse(%d,%d,%d), needs=purse(0,0,0,%d)},' %
            (json.dumps(key),json.dumps(name),json.dumps(category),stars,json.dumps(entry['about']),json.dumps(path.removeprefix('data/')),w,h,*pivot,entry['base_width'],*entry['cost'],stars))
    lua.append('}')
    (ROOT/'lua/buildings.lua').write_text('\n'.join(lua)+'\n')
    (ART/'manifest.json').write_text(json.dumps(dict(source='art/building-catalogue/paintover-atlas.png',
        registration='art/building-catalogue/registration.json',items=entries),indent=2)+'\n')
    print(f'Exported {len(entries)} registered building sprites')


if __name__ == '__main__':
    main()

"""Register independent Blender ground shadows to the current painted catalogue.

Only spatial crops and shadow registration resize are applied. The 96 current
painted sprites and their authored alpha are never rewritten by this exporter.
"""
import argparse
import json
from pathlib import Path

from PIL import Image

GAME = Path(__file__).resolve().parents[1]
ART = GAME / 'art/isometric-paintover'


def image_output(im, path, check):
    if check:
        actual = Image.open(path)
        assert actual.mode == 'RGBA' and actual.size == im.size and actual.tobytes() == im.tobytes(), f'Stale building asset: {path}'
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        im.save(path, optimize=True)


def text_output(value, path, check):
    if check:
        assert path.read_text() == value, f'Stale building registration: {path}'
    else:
        path.write_text(value)


def main(check=False):
    layout = json.loads((GAME / 'art/isometric-blender/scene_layout.json').read_text())
    catalogue = json.loads((GAME / 'art/building-catalogue/manifest.json').read_text())['items']
    assert layout['slope'] == .5 and layout['grid_max_error_px'] < .001
    entries = []
    lua = ['-- Generated by tools/building_assets.py; shadows share catalogue pixel density.', 'return {']
    for i, (b, item) in enumerate(zip(layout['buildings'], layout['items'])):
        # ID 4 is now a dry courtyard. Never attach the retired bridge's shadow.
        if i == 4:
            continue
        current = catalogue[i]
        assert current['key'] == b['key'] and current['size'] == [b['w'], b['h']]
        density = current['base_width'] / ((b['w'] + b['h']) * 60)
        canvas = tuple(round(n * density) for n in layout['resolution'])
        sx, sy = (canvas[j] / layout['resolution'][j] for j in range(2))
        px = (layout['origin_px'][0] + (item['cu'] - item['cv']) * 60) * sx
        py = (layout['origin_px'][1] + (item['cu'] + item['cv']) * 30) * sy
        shadow = Image.open(ART / f'shadows/{i}.png').convert('RGBA')
        assert shadow.size == tuple(layout['resolution'])
        shadow = shadow.resize(canvas, Image.Resampling.LANCZOS)
        box = shadow.getchannel('A').point(lambda a: 255 if a > 4 else 0).getbbox()
        assert box and shadow.getchannel('A').getextrema()[1] > 32
        box = (max(0, box[0] - 8), max(0, box[1] - 8),
               min(shadow.width, box[2] + 8), min(shadow.height, box[3] + 8))
        shadow = shadow.crop(box)
        pivot = [round(px - box[0], 4), round(py - box[1], 4)]
        path = f'data/building-shadows/{i}.png'
        image_output(shadow, GAME / path, check)
        entries.append(dict(id=i, key=b['key'], size=current['size'],
                            shadow=path, shadow_crop=list(box), canvas=list(canvas),
                            registration_scale=[sx, sy], shadow_pivot=pivot,
                            base_width=current['base_width']))
        lua.append(f'    [{i+1}] = {{shadow_path="building-shadows/{i}.png", '
                   f'shadow_pivot=vec2({pivot[0]}, {pivot[1]}), base_width={current["base_width"]}}} , -- {b["key"]}')
    lua.append('}')
    meta = dict(shadow_source='shadows/0..9.png',
                sprite_registration='../building-catalogue/manifest.json',
                excluded={'4': 'Sunstone courtyard supersedes the bridge; no compatible independent shadow'},
                pixel_operations='Lanczos resize and spatial crop of rendered shadows; no sprite changes',
                assets=entries)
    text_output(json.dumps(meta, indent=2) + '\n', ART / 'registration.json', check)
    text_output('\n'.join(lua) + '\n', GAME / 'lua/building_art.lua', check)
    print('Building assets: nine separate shadows registered to the 96-entry catalogue' + (' (verified)' if check else ''))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    main(parser.parse_args().check)

"""Extract the authored atlas and register independent Blender ground shadows.

Only spatial crops and shadow registration resize are applied. Painted RGB/alpha
are copied directly from the transparent ImageGen master, never recoloured.
"""
from collections import deque
import argparse
import json
import math
from pathlib import Path

from PIL import Image

GAME = Path(__file__).resolve().parents[1]
ART = GAME / 'art/isometric-paintover'


def component_boxes(im):
    w, h = im.size
    alpha = im.getchannel('A').tobytes()
    seen = bytearray(w * h)
    boxes = []
    for start, a in enumerate(alpha):
        if a <= 45 or seen[start]:
            continue
        queue = deque([start])
        seen[start] = 1
        x0, y0, x1, y1, count = w, h, 0, 0, 0
        while queue:
            p = queue.popleft()
            x, y = p % w, p // w
            x0, y0, x1, y1 = min(x0, x), min(y0, y), max(x1, x + 1), max(y1, y + 1)
            count += 1
            neighbours = ([p - 1] if x else []) + ([p + 1] if x + 1 < w else [])
            neighbours += ([p - w] if y else []) + ([p + w] if y + 1 < h else [])
            for n in neighbours:
                if not seen[n] and alpha[n] > 45:
                    seen[n] = 1
                    queue.append(n)
        if count > 2000:
            boxes.append((max(0, x0 - 3), max(0, y0 - 3), min(w, x1 + 3), min(h, y1 + 3)))
    assert len(boxes) == 10, f'Expected ten separated painted buildings, found {len(boxes)}'
    return boxes


def image_output(im, path, check):
    if check:
        actual = Image.open(path)
        assert actual.mode == 'RGBA' and actual.size == im.size and actual.tobytes() == im.tobytes(), f'Stale building asset: {path}'
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        im.save(path, optimize=True)


def text_output(value, path, check):
    if check:
        assert path.read_text() == value, f'Stale building registration: {path}'
    else:
        path.write_text(value)


def main(check=False):
    atlas = Image.open(ART / 'buildings-transparent.png').convert('RGBA')
    layout = json.loads((GAME / 'art/isometric-blender/scene_layout.json').read_text())
    assert layout['slope'] == .5 and layout['grid_max_error_px'] < .001
    sx, sy = atlas.width / layout['resolution'][0], atlas.height / layout['resolution'][1]
    boxes = component_boxes(atlas)
    used = set()
    entries = []
    lua = ['-- Generated by tools/building_assets.py; pixel pivots share one world scale.', 'return {']
    for i, (b, item) in enumerate(zip(layout['buildings'], layout['items'])):
        px = (layout['origin_px'][0] + (item['cu'] - item['cv']) * 60) * sx
        py = (layout['origin_px'][1] + (item['cu'] + item['cv']) * 30) * sy
        matches = [box for box in boxes if box[0] <= px < box[2] and box[1] <= py < box[3]]
        assert len(matches) == 1, f'Painted ground pivot does not identify {b["key"]}'
        box = matches[0]
        assert box not in used
        used.add(box)
        sprite = atlas.crop(box)
        shadow = Image.open(ART / f'shadows/{i}.png').convert('RGBA')
        assert shadow.size == tuple(layout['resolution'])
        shadow = shadow.resize(atlas.size, Image.Resampling.LANCZOS)
        # A tiny Cycles/denoiser alpha residual can cover the render border.
        # Crop the meaningful shadow with 8px feather margin; do not edit alpha.
        shadow_box = shadow.getchannel('A').point(lambda a: 255 if a > 4 else 0).getbbox()
        assert shadow_box and shadow.getchannel('A').getextrema()[1] > 32
        shadow_box = (max(0, shadow_box[0] - 8), max(0, shadow_box[1] - 8),
                      min(shadow.width, shadow_box[2] + 8), min(shadow.height, shadow_box[3] + 8))
        shadow = shadow.crop(shadow_box)
        pivot = [round(px - box[0], 4), round(py - box[1], 4)]
        shadow_pivot = [round(px - shadow_box[0], 4), round(py - shadow_box[1], 4)]
        width = round((b['w'] + b['h']) * 60 * sx, 4)
        image_output(sprite, GAME / f'data/buildings/{i}.png', check)
        image_output(shadow, GAME / f'data/building-shadows/{i}.png', check)
        entries.append(dict(id=i, key=b['key'], size=[b['w'], b['h']], sprite=f'data/buildings/{i}.png',
                            shadow=f'data/building-shadows/{i}.png', sprite_crop=list(box), shadow_crop=list(shadow_box),
                            pivot=pivot, shadow_pivot=shadow_pivot, base_width=width))
        lua.append(f'    {{size=size2({b["w"]}, {b["h"]}), pivot=vec2({pivot[0]}, {pivot[1]}), '
                   f'base_width={width}, shadow_pivot=vec2({shadow_pivot[0]}, {shadow_pivot[1]})}}, -- {b["key"]}')
    lua.append('}')
    meta = dict(source='buildings-transparent.png', shadow_source='shadows/0..9.png',
                atlas_size=list(atlas.size), source_camera_size=layout['resolution'],
                shadow_registration_scale=[sx, sy], pixel_operations='painted sprite crop only; Lanczos resize and crop of rendered shadows',
                assets=entries)
    text_output(json.dumps(meta, indent=2) + '\n', ART / 'registration.json', check)
    text_output('\n'.join(lua) + '\n', GAME / 'lua/building_art.lua', check)
    print('Building assets: ten authored sprites and ten separate shadows registered' + (' (verified)' if check else ''))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    main(parser.parse_args().check)

"""Fit every Relic Rush board to the difficulty curve in lua/difficulty.lua.

Simulates the real rules with a greedy bot on seeded starts (tools/tune_levels.lua)
and writes lua/level_tuning.lua, which campaign.lua applies, plus a review table in
docs/level-tuning.md. Levels run in parallel worker processes; this is an offline
authoring tool, not a test.

    make build/test/engine
    python3 games/relic-rush/tools/tune_levels.py              # every level
    python3 games/relic-rush/tools/tune_levels.py --levels 5,9,11-15 --seeds 30

Run one tuner at a time: each run merges into docs/level-tuning.json.
"""
import argparse
import concurrent.futures
import json
import os
from pathlib import Path
import subprocess
import time

GAME = Path(__file__).resolve().parents[1]
ROOT = GAME.parents[1]
LEVELS = 30


def run(first, last, seeds):
    home = ROOT / f'build/tune-levels-home/{first}'
    home.mkdir(parents=True, exist_ok=True)
    out = subprocess.run(
        [str(ROOT / 'build/test/engine'), '--script', 'games/relic-rush/tools/tune_levels.lua',
         '--tune-levels', f'{first}-{last}', '--tune-seeds', str(seeds)],
        cwd=ROOT, env={**os.environ, 'SPRITE_SAVE_DIR': str(home)},
        text=True, capture_output=True, check=True).stdout
    rows = [json.loads(line.removeprefix('TUNE_JSON ')) for line in out.splitlines()
            if line.startswith('TUNE_JSON ')]
    assert len(rows) == last - first + 1, out
    return rows


def merge(rows):
    """Every level's latest fit, so a partial run refreshes the whole report."""
    path = GAME / 'docs/level-tuning.json'
    merged = {r['level']: r for r in json.loads(path.read_text())} if path.exists() else {}
    merged.update({r['level']: r for r in rows})
    rows = [merged[k] for k in sorted(merged)]
    path.write_text(json.dumps(rows, indent=1, sort_keys=True, ensure_ascii=False) + '\n')
    return rows


def write_tuning(rows, seeds):
    path = GAME / 'lua/level_tuning.lua'
    lines = ['-- Generated by games/relic-rush/tools/tune_levels.py from lua/difficulty.lua.',
             f'-- Greedy-bot fit, {seeds} seeds per search step. Do not edit by hand.',
             'return {']
    for r in rows:
        lines.append(f"    [{r['level']}] = {{chains={r['chains']}, double_chains={r['double_chains']}, "
                     f"double_tablets={r['tablets']}, moves={r['moves']}}},   -- {r['tier']}")
    lines.append('}')
    path.write_text('\n'.join(lines) + '\n')


def write_report(rows, seeds):
    path = GAME / 'docs/level-tuning.md'
    head = ['# Level tuning', '',
            'Generated by `python3 games/relic-rush/tools/tune_levels.py` from the curve in',
            '[lua/difficulty.lua](../lua/difficulty.lua). A greedy bot (highest-valued legal swap,',
            'no tools) plays hashed-seed starts with every board spawning six kinds and refill',
            'damping from the second cascade wave. Its rates order and space the boards; they',
            'are not measured human win rates. Median and fastest count the bot\'s winning games.',
            '',
            '| # | Board | Tier | Chains (double) | Green tablets | Moves (curve) | Bot win (target) | Median | Fastest | Won in ≤3 | Notes |',
            '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    body = []
    for r in sorted(rows, key=lambda r: r['level']):
        body.append(f"| {r['level']} | {r['name']} | {r['tier']} | {r['chains']} ({r['double_chains']}) | "
                    f"{r['tablets']} | {r['moves']} ({r['target_moves']}) | {r['bot_win']:.0%} ({r['target_win']:.0%}) | "
                    f"{r['median']} | {r['fastest']} | {r['won_in_3']:.0%} | {r['note']} |")
    path.write_text('\n'.join(head + body) + f'\n\n{seeds} starts per search step; the fit is re-measured on '
                    f'{seeds * 2} fresh starts.\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--levels', default=f'1-{LEVELS}')
    parser.add_argument('--seeds', type=int, default=30)
    parser.add_argument('--jobs', type=int, default=os.cpu_count() or 4)
    args = parser.parse_args()
    levels = []
    for part in args.levels.split(','):
        first, _, last = part.partition('-')
        levels += range(int(first), int(last or first) + 1)
    started = time.monotonic()
    with concurrent.futures.ThreadPoolExecutor(args.jobs) as pool:
        chunks = pool.map(lambda n: run(n, n, args.seeds), levels)
        rows = [row for chunk in chunks for row in chunk]
    merged = merge(rows)
    write_tuning(merged, args.seeds)
    write_report(merged, args.seeds)
    for r in rows:
        print(f"{r['level']:2} {r['tier']:8} chains={r['chains']:2}({r['double_chains']}) tablets={r['tablets']:2} moves={r['moves']:3} "
              f"bot_win={r['bot_win']:.0%} {r['note']}")
    print(f'{len(rows)} levels in {time.monotonic() - started:.0f} s')


if __name__ == '__main__':
    main()

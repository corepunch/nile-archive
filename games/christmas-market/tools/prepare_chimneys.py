#!/usr/bin/env python3
"""Import the local chimney edits and generate their smoke outlet coordinates."""
import argparse
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "art/building-catalogue/chimneys"


def feather(box, canvas):
    """Blend the seam into the original roof, with full coverage at canvas edges."""
    left, top, right, bottom = box
    w, h = right - left, bottom - top
    mask = Image.new("L", (w, h))
    mask.putdata([
        min(255, 64 * min(x if left else w, y if top else h,
                          w - 1 - x if right < canvas[0] else w,
                          h - 1 - y if bottom < canvas[1] else h))
        for y in range(h) for x in range(w)
    ])
    return mask


def prepare(check):
    layout = json.loads((SOURCES / "layout.json").read_text())
    with Image.open(SOURCES / "output.png") as output, Image.open(SOURCES / "original-crops.png") as original:
        edited = output.convert("RGBA").resize(tuple(layout["guide_size"]), Image.Resampling.LANCZOS)
        lua = ["-- Generated by tools/prepare_chimneys.py from the reviewed paint-over.", "return {"]
        for key, entry in layout["buildings"].items():
            path = ROOT / "data/city/buildings" / f"{key}.png"
            with Image.open(path) as current:
                sprite = current.convert("RGBA")
            assert list(sprite.size) == entry["image"], f"{key}: chimney art needs registration to the new canvas"
            box = tuple(entry["target"])
            previous = original.crop(entry["original"])
            patch = edited.crop(entry["guide"]).resize(previous.size, Image.Resampling.LANCZOS)
            detail = Image.composite(patch, previous, feather(box, sprite.size))
            x, y, width = entry["outlet"]
            r, g, b, a = detail.getpixel((x - box[0], y - box[1]))
            assert a >= 240 and max(r, g, b) < 120 and width > 0, f"{key}: outlet must be inside the dark flue"
            if check:
                assert sprite.crop(box).tobytes() == detail.tobytes(), f"{key}: stale chimney paint-over"
            else:
                sprite.paste(detail, box)
                sprite.save(path)
            lua.append(f"    {key} = {{x = {x}, y = {y}, width = {width}}},")
        lua.append("}")
    generated = ROOT / "lua/chimney_flues.lua"
    registered = "\n".join(lua) + "\n"
    if check:
        assert generated.read_text() == registered, "stale chimney outlet coordinates"
    else:
        generated.write_text(registered)
    print(f"Christmas Market: {len(layout['buildings'])} painted chimney openings")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    prepare(parser.parse_args().check)

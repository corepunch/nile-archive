"""Christmas Market's catalogue around its rendered sprites. Runs after tools/buildings.py.

    python3 games/christmas-market/tools/prepare_catalogue.py [--inventory] [--check]

catalogue.json owns names, categories, prices, Star unlocks and descriptions; the
Blender registry owns the art. Writes lua/buildings.lua, which merges the generated
lua/building_sprites.lua by key, and the manifest. --inventory prints the runtime
inventory rows of docs/building-catalogue.md; --check only verifies that everything
is current.

Row order is save data: the city stores a building's type, its row index.
The first ten rows are the campaign's market wishes, then the decorations.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'art/building-catalogue'
LUA = ROOT / 'lua/buildings.lua'
FIRST_KEYS = ['arch', 'lumber', 'bakery', 'cocoa', 'toys', 'gifts', 'candles', 'carousel', 'rink', 'tree', 'firs', 'bench']

catalogue = json.loads((ART / 'catalogue.json').read_text())
registry = json.loads((ART / 'registration.json').read_text())
assert [row[0] for row in catalogue[:12]] == FIRST_KEYS, 'the first twelve rows are save data: never reorder them'
assert len(registry['items']) == len(catalogue), 'render every catalogue object first'
assert [row[0] for row in catalogue] == registry['order'], 'catalogue order is save data'
check = '--check' in sys.argv

manifest = ART / 'manifest.json'
entries, lua = [], ['-- Generated by tools/prepare_catalogue.py; do not edit.',
                    'local sprites = require("building_sprites")', 'local items = {']
for i, (key, name, category, w, h, cost, stars, about) in enumerate(catalogue):
    art = registry['items'][key]
    assert art['size'] == [w, h], key
    needs = 'purse()' if category == 'wonder' or not stars else 'purse(0,0,0,%d)' % stars
    entries.append(dict(id=i, key=key, name=name, category=category, size=[w, h], pivot=art['pivot'], base_width=art['base_width'],
                        cost=cost, stars=stars, about=about, image=art['image'], runtime=art['sprite'], shadow=art['shadow'],
                        source=registry['master'] + '#' + key))
    lua.append('    {key=%s,name=%s,category=%s,stars=%d,about=%s,cost=purse(%s),needs=%s},' % (
        json.dumps(key), json.dumps(name, ensure_ascii=False), json.dumps(category), stars,
        json.dumps(about, ensure_ascii=False), ','.join(str(c) for c in cost), needs))
lua += ['}', 'for _, b in ipairs(items) do', '    for field, value in pairs(sprites[b.key]) do b[field] = value end', 'end', 'return items']
text = '\n'.join(lua) + '\n'
doc = json.dumps(dict(source=registry['master'], registration='art/building-catalogue/registration.json',
                      camera=registry['camera'], items=entries), indent=1, ensure_ascii=False) + '\n'
if check:
    assert LUA.read_text() == text, 'lua/buildings.lua is stale: run tools/prepare_catalogue.py'
    assert manifest.read_text() == doc, 'art/building-catalogue/manifest.json is stale: run tools/prepare_catalogue.py'
    print('Christmas Market catalogue: %d Blender-rendered objects match their registration' % len(entries))
else:
    LUA.write_text(text)
    manifest.write_text(doc)
    print('prepared', len(entries), 'objects')
if '--inventory' in sys.argv:
    for e in entries:
        page = e['id'] // 4 + 1   # --building-review shows four objects a page
        cost = ' / '.join(str(c) for c in e['cost'])
        print('| %d / `%s` | %s | %s | %d x %d | %s | %d | [Page %d](screenshots/building-review-%d.jpg) |' % (
            e['id'], e['key'], e['name'], e['category'], *e['size'], cost, e['stars'], page, page))

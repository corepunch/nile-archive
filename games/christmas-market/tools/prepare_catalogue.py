"""Crop the rendered catalogue sprites and generate the game's building table.

    python3 games/christmas-market/tools/prepare_catalogue.py [--inventory] [--check]

Reads art/building-catalogue/catalogue.json (names, categories, footprints,
prices, Star unlocks, descriptions) and registration.json (each render's
projected pivot and base width, written by render_buildings.py). Each
data/buildings/<key>.png is cropped to its visible pixels; retained pixels keep
their rendered RGBA. The pivot moves with the crop. Writes lua/buildings.lua,
art/building-catalogue/manifest.json and the contact sheet geometry-atlas.png
(see docs/BUILDING_ART.md). --inventory prints the runtime inventory rows of
docs/building-catalogue.md; --check only verifies that everything is current.

Row order is save data: the city stores a building's type, its row index.
The first ten rows are the campaign's market wishes, then the decorations.
"""
import json
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'art/building-catalogue'
DATA = ROOT / 'data/buildings'
LUA = ROOT / 'lua/buildings.lua'
CELL, COLS = 288, 8
FIRST_KEYS = ['arch', 'lumber', 'bakery', 'cocoa', 'toys', 'gifts', 'candles', 'carousel', 'rink', 'tree', 'firs', 'bench']

catalogue = json.loads((ART / 'catalogue.json').read_text())
registration = json.loads((ART / 'registration.json').read_text())
assert [row[0] for row in catalogue[:12]] == FIRST_KEYS, 'the first twelve rows are save data: never reorder them'
assert len(registration['items']) == len(catalogue), 'render every catalogue object first'
assert registration['tile_px'] == 128
check = '--check' in sys.argv

manifest = ART / 'manifest.json'
previous = {e['key']: e for e in json.loads(manifest.read_text())['items']} if manifest.exists() else {}
entries, lua = [], ['-- Generated by tools/prepare_catalogue.py; do not edit.',
                    '-- Blender renders of art/building-catalogue/christmas_market_buildings.blend (docs/building-catalogue.md).',
                    'return {']
rows = (len(catalogue) + COLS - 1) // COLS
sheet = Image.new('RGBA', (COLS * CELL, rows * CELL), (0, 0, 0, 0))
for i, (key, name, category, w, h, cost, stars, about) in enumerate(catalogue):
    reg = registration['items'][key]
    assert reg['size'] == [w, h], key
    path = DATA / (key + '.png')
    image = Image.open(path).convert('RGBA')
    if list(image.size) == reg['image']:   # a fresh render: crop it once
        assert not check, key + ' is an uncropped render: run prepare_catalogue.py'
        box = image.getchannel('A').point(lambda a: 255 if a > 2 else 0).getbbox()
        assert box, key + ' rendered empty'
        image = image.crop(box)
        image.save(path, optimize=True)
        crop = box[:2]
    else:                                  # cropped by an earlier run
        crop = previous[key]['crop']
        assert list(image.size) == previous[key]['image'], key + ': the sprite does not match the manifest'
    pivot = [reg['pivot'][0] - crop[0], reg['pivot'][1] - crop[1]]
    base = reg['base_width']
    wonder = category == 'wonder'
    needs = 'purse()' if wonder or not stars else 'purse(0,0,0,%d)' % stars
    entries.append(dict(id=i, key=key, name=name, category=category, size=[w, h], pivot=pivot, base_width=base,
                        cost=cost, stars=stars, about=about, image=list(image.size), crop=list(crop),
                        runtime='data/buildings/' + key + '.png',
                        source='art/building-catalogue/christmas_market_buildings.blend#cm_' + key))
    lua.append('    {key=%s,name=%s,category=%s,stars=%d,about=%s,sprite_path=%s,size=size2(%d,%d),pivot=vec2(%g,%g),base_width=%g,cost=purse(%s),needs=%s},' %
               (json.dumps(key), json.dumps(name, ensure_ascii=False), json.dumps(category), stars,
                json.dumps(about, ensure_ascii=False), json.dumps('buildings/' + key + '.png'), w, h, *pivot, base,
                ','.join(str(c) for c in cost), needs))
    scale = min((CELL - 24) / image.width, (CELL - 24) / image.height)
    fit = image.resize((round(image.width * scale), round(image.height * scale)), Image.Resampling.LANCZOS)
    cx, cy = i % COLS * CELL, i // COLS * CELL
    sheet.alpha_composite(fit, (cx + (CELL - fit.width) // 2, cy + CELL - 12 - fit.height))
lua.append('}')
text = '\n'.join(lua) + '\n'
doc = json.dumps(dict(source='art/building-catalogue/christmas_market_buildings.blend',
                      registration='art/building-catalogue/registration.json', tile_px=128, items=entries),
                 indent=1, ensure_ascii=False) + '\n'
if check:
    assert LUA.read_text() == text, 'lua/buildings.lua is stale: run tools/prepare_catalogue.py'
    assert manifest.read_text() == doc, 'art/building-catalogue/manifest.json is stale: run tools/prepare_catalogue.py'
    print('Christmas Market catalogue: %d Blender-rendered objects match their registration' % len(entries))
else:
    LUA.write_text(text)
    manifest.write_text(doc)
    sheet.save(ART / 'geometry-atlas.png', optimize=True)
    print('prepared', len(entries), 'objects')
if '--inventory' in sys.argv:
    for e in entries:
        page = e['id'] // 4 + 1   # --building-review shows four objects a page
        cost = ' / '.join(str(c) for c in e['cost'])
        print('| %d / `%s` | %s | %s | %d x %d | %g, %g | %g | %s | %d | [Page %d](screenshots/building-review-%d.jpg) |' % (
            e['id'], e['key'], e['name'], e['category'], *e['size'], *e['pivot'], e['base_width'], cost, e['stars'], page, page))

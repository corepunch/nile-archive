-- New hidden-object scenes use 1536x1024 source-image coordinates scaled to
-- the game's 1200x800 scene space. All targets are authored into the artwork.
local function points(raw)
    local result = {}
    for i, p in ipairs(raw) do result[i] = vec2(p[1] * 1200 / 1536, p[2] * 800 / 1024) end
    return result
end

local function scene(title, teaser, clues, background, names, at, radius)
    return {title = title, teaser = teaser, clues = clues, background = background,
            names = names, at = points(at), radius = points(radius)}
end


"""Crop the rendered catalogue sprites and generate the game's tables.

    python3 games/nile-archive/tools/prepare_catalogue.py [--inventory]

Reads art/building-catalogue/catalogue.json (names, categories, footprints,
prices, Star unlocks) and registration.json (each render's projected pivot and
base width, written by render_buildings.py). Each data/buildings/<key>.png is
cropped to its visible pixels; retained pixels keep their rendered RGBA. The
pivot moves with the crop. Writes lua/archive_catalogue.lua, the manifest and a 12 x 8
contact sheet (geometry-atlas.png) laid out like Relic Rush's paint-over guide.
--inventory also prints the runtime inventory rows of docs/building-catalogue.md.
"""
import json
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'art/building-catalogue'
DATA = ROOT / 'data/buildings'
CELL, COLS, ROWS = 288, 12, 8

catalogue = json.loads((ART / 'catalogue.json').read_text())
registration = json.loads((ART / 'registration.json').read_text())
assert len(catalogue) == len(registration['items']) == 96, 'render every catalogue object first'
assert registration['tile_px'] == 128

manifest = ART / 'manifest.json'
previous = {e['key']: e for e in json.loads(manifest.read_text())['items']} if manifest.exists() else {}
entries, lua = [], ['-- Generated by tools/prepare_catalogue.py; do not edit.',
                    '-- Blender renders of art/building-catalogue/nile_archive_buildings.blend.',
                    'return {']
sheet = Image.new('RGBA', (COLS * CELL, ROWS * CELL), (0, 0, 0, 0))
for i, (key, name, category, w, h, coins, stars, note) in enumerate(catalogue):
    reg = registration['items'][key]
    assert reg['size'] == [w, h], key
    path = DATA / (key + '.png')
    image = Image.open(path).convert('RGBA')
    if list(image.size) == reg['image']:   # a fresh render: crop it once
        box = image.getchannel('A').point(lambda a: 255 if a > 2 else 0).getbbox()
        assert box, key + ' rendered empty'
        image = image.crop(box)
        image.save(path, optimize=True)
        crop = box[:2]
    else:                                  # cropped by an earlier run
        crop = previous[key]['crop']
    pivot = [reg['pivot'][0] - crop[0], reg['pivot'][1] - crop[1]]
    base = reg['base_width']
    entries.append(dict(id=i, key=key, name=name, category=category, size=[w, h], pivot=pivot,
                        base_width=base, coins=coins, stars=stars, note=note, image=list(image.size), crop=list(crop),
                        runtime='data/buildings/' + key + '.png',
                        source='art/building-catalogue/nile_archive_buildings.blend#na_' + key))
    lua.append('    {key=%s, name=%s, category=%s, stars=%d, sprite_path=%s, size=size2(%d,%d), pivot=vec2(%g,%g), base_width=%g, coins=%d},' %
               (json.dumps(key), json.dumps(name, ensure_ascii=False), json.dumps(category), stars,
                json.dumps('buildings/' + key + '.png'), w, h, *pivot, base, coins))
    # contact sheet: each object scaled to fill its cell, bottom-centred
    scale = min((CELL - 24) / image.width, (CELL - 24) / image.height)
    fit = image.resize((round(image.width * scale), round(image.height * scale)), Image.Resampling.LANCZOS)
    cx, cy = i % COLS * CELL, i // COLS * CELL
    sheet.alpha_composite(fit, (cx + (CELL - fit.width) // 2, cy + CELL - 12 - fit.height))
lua.append('}')
(ROOT / 'lua/archive_catalogue.lua').write_text('\n'.join(lua) + '\n')
manifest.write_text(json.dumps(dict(source='art/building-catalogue/nile_archive_buildings.blend',
    registration='art/building-catalogue/registration.json', tile_px=128, items=entries), indent=1, ensure_ascii=False) + '\n')
sheet.save(ART / 'geometry-atlas.png', optimize=True)
print('prepared', len(entries), 'objects')
if '--inventory' in sys.argv:
    for e in entries:
        page = e['id'] // 8 + 1   # --building-review shows eight objects a page
        print('| %d / `%s` | %s | %s | %d x %d | %g, %g | %g | %d | %d | [Page %d](review/building-catalogue/footprints-%02d.jpg) |' % (
            e['id'] + 5, e['key'], e['name'], e['category'], *e['size'], *e['pivot'], e['base_width'], e['coins'], e['stars'], page, page))

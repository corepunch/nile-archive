"""Nile Archive's catalogue around its rendered sprites. Runs after tools/buildings.py.

    python3 games/nile-archive/tools/prepare_catalogue.py [--inventory]

catalogue.json owns names, categories, prices and Star unlocks; the Blender registry
owns the art. Writes lua/archive_catalogue.lua, which merges the generated
lua/building_sprites.lua by key, and the manifest. --inventory also prints the
runtime inventory rows of docs/building-catalogue.md.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'art/building-catalogue'
RESTORATIONS = 5   # saves store a decoration's type as RESTORATIONS + its row: append only

catalogue = json.loads((ART / 'catalogue.json').read_text())
registry = json.loads((ART / 'registration.json').read_text())
assert len(catalogue) == 96 and len(registry['items']) == RESTORATIONS + 96, 'render every object first'
assert [row[0] for row in catalogue] == registry['order'][RESTORATIONS:], 'catalogue order is save data'

entries, lua = [], ['-- Generated by tools/prepare_catalogue.py; do not edit.',
                    'local sprites = require("building_sprites")', 'local items = {']
for i, (key, name, category, w, h, coins, stars, note) in enumerate(catalogue):
    art = registry['items'][key]
    assert art['size'] == [w, h], key
    entries.append(dict(id=i, key=key, name=name, category=category, size=[w, h], pivot=art['pivot'],
                        base_width=art['base_width'], scale=art['scale'], coins=coins, stars=stars, note=note, image=art['image'],
                        runtime=art['sprite'], shadow=art['shadow'], source=registry['master'] + '#' + key))
    lua.append('    {key=%s, name=%s, category=%s, stars=%d, coins=%d},' % (
        json.dumps(key), json.dumps(name, ensure_ascii=False), json.dumps(category), stars, coins))
lua += ['}', 'for _, b in ipairs(items) do', '    for field, value in pairs(sprites[b.key]) do b[field] = value end', 'end', 'return items']
(ROOT / 'lua/archive_catalogue.lua').write_text('\n'.join(lua) + '\n')
(ART / 'manifest.json').write_text(json.dumps(dict(source=registry['master'], registration='art/building-catalogue/registration.json',
    camera=registry['camera'], items=entries), indent=1, ensure_ascii=False) + '\n')
print('prepared', len(entries), 'objects')
if '--inventory' in sys.argv:
    for e in entries:
        page = e['id'] // 8 + 1   # --building-review shows eight objects a page
        print('| %d / `%s` | %s | %s | %d x %d | %d | %d | [Page %d](review/building-catalogue/footprints-%02d.jpg) |' % (
            e['id'] + RESTORATIONS, e['key'], e['name'], e['category'], *e['size'], e['coins'], e['stars'], page, page))

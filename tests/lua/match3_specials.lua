local E, H = require("match3"), require("support")
local t = H.suite("optional match-3 specials")
local function fixture(names)
    local R = E.new{special_rules=names}
    return R,H.board(R),R.new_match()
end
local function step(R, cell, axis, count)
    for _=1,count do cell=R.hex_neighbor(cell,axis) end
    return cell
end
local function run(R,g,cell,axis,length)
    for k=0,length-1 do g.tiles[step(R,cell,axis,k)]=R.tile(1) end
end
for _,name in ipairs{"striped","color_bomb"} do
    for axis=0,2 do
        for _,reverse in ipairs{false,true} do
            t:case(name .. " swap on axis " .. axis .. " reverse=" .. tostring(reverse),function()
                local R,g,m=fixture({name})
                local center=R.hex_center()
                local first=step(R,center,axis+3,2)
                local donor=R.hex_neighbor(center,(axis+1)%3)
                run(R,g,first,axis,name=="striped" and 4 or 5)
                g.tiles[center],g.tiles[donor]=R.tile(2),R.tile(1)
                local a,b=donor,center
                if reverse then a,b=b,a end
                t:check(R.game_swap_matches(g,a,b),"hint sees valid move")
                t:check(R.game_swap(g,a,b,m),"swap accepted")
                R.game_apply(g,m)
                t:check(g.tiles[center].special==name,"make special at matched swapped cell")
                local copy=R.game_copy(g)
                t:check(copy.tiles[center].special==name,"simulation preserves special")
                local to=R.hex_neighbor(center,axis)
                local target=R.hex_index(0,-3)
                if name=="striped" then target=step(R,to,axis,1) end
                g.tiles[to],g.tiles[target]=R.tile(2),R.tile(2)
                if name=="striped" then
                    -- A line gem keeps its color: it waits for a match of its kind.
                    t:check(g.tiles[center].kind==1,"line gem keeps its color")
                    t:check(not R.game_swap_matches(g,center,to) and not R.game_swap(g,center,to,m),
                        "a plain swap does not fire a colored special")
                    local side=(axis+1)%R.AXES
                    g.tiles[step(R,center,side,1)],g.tiles[step(R,center,side,2)]=R.tile(1),R.tile(1)
                    R.game_matches(g,m)
                    t:check(m.hits==3 and m.mask[center] and not m.mask[target],"line gem matches as its color")
                else
                    t:check(R.game_swap(g,center,to,m),"activate without a color match")
                end
                R.game_apply(g,m)
                t:check(m.mask[target] and m.special_effects[1].name==name,"effect hits target and emits event")
                t:check(g.tiles[target].kind==-1 and g.tiles[to].kind==-1 and g.tiles[center].kind==-1,
                    "target and special are consumed")
            end)
        end
    end
end
for axis=0,2 do
    t:case("rhombus axis " .. axis,function()
        for _,enabled in ipairs{false,true} do
            local R,g,m=fixture(enabled and {"plane"} or {})
            local c=R.hex_center()
            local a,b=R.hex_neighbor(c,axis),R.hex_neighbor(c,axis+1)
            local d=R.hex_neighbor(a,axis+1)
            local donor=R.hex_neighbor(c,axis+3)
            for _,i in ipairs{a,b,d,donor} do g.tiles[i]=R.tile(1) end
            g.tiles[c]=R.tile(2)
            t:check(R.game_swap_matches(g,donor,c)==enabled,"hint agrees with enabled rule")
            t:check(R.game_swap(g,donor,c,m)==enabled,"rhombus only when enabled")
            if enabled then
                R.game_apply(g,m)
                t:check(g.tiles[c].special=="plane","plane created at swapped cell")
                local target=R.hex_index(0,-3)
                g.tiles[a],g.tiles[target]=R.tile(3),R.tile(2)
                g.oil[target],g.oil_left=1,1
                t:check(R.game_swap(g,c,a,m),"plane can be launched")
                t:check(m.special_effects[1].target==target,"plane seeks plaque")
                R.game_apply(g,m)
                t:check(g.oil_left==0,"plane clears plaque on impact")
            end
        end
    end)
end
t:case("T shape and bomb blast",function()
    local R,g,m=fixture({"t_bomb"})
    local c=R.hex_center()
    run(R,g,R.hex_neighbor(c,3),0,3)
    run(R,g,c,1,3)
    local donor=R.hex_neighbor(c,2)
    g.tiles[c],g.tiles[donor]=R.tile(2),R.tile(1)
    t:check(R.game_probe_swap(g,donor,c,m),"T can be previewed")
    t:check(m.special_awards and m.special_awards[c] and m.special_awards[c].name=="t_bomb",
        "preview includes the crossing award from two short runs")
    t:check(R.game_swap(g,donor,c,m),"T swap is accepted")
    t:check(m.hits==5,"T clears five distinct cells")
    R.game_apply(g,m)
    t:check(g.tiles[c].special=="t_bomb","T awards bomb")
    local a=R.hex_neighbor(c,0)
    local target=R.hex_neighbor(a,1)
    g.tiles[a],g.tiles[target]=R.tile(3),R.tile(2)
    t:check(R.game_swap(g,c,a,m),"activate bomb")
    t:check(m.mask[target] and m.special_effects[1].name=="t_bomb","bomb hits its neighbors")
end)
t:case("ordinary long lines by default",function()
    local R,g,m=fixture({})
    local c=R.hex_center()
    run(R,g,step(R,c,3,2),0,5)
    R.game_matches(g,m)
    t:check(m.hits==5 and m.special_awards==nil,"no implicit bonuses")
end)
t:case("two specials chained once each",function()
    local R,g,m=fixture({"striped","t_bomb"})
    local c=R.hex_center()
    local a=R.hex_neighbor(c,0)
    local b=R.hex_neighbor(a,0)
    local target=R.hex_neighbor(b,1)
    g.tiles[c],g.tiles[a]=R.tile(1,"striped",0),R.tile(2)
    g.tiles[b],g.tiles[target]=R.tile(2,"t_bomb"),R.tile(3)
    g.tiles[step(R,c,1,1)],g.tiles[step(R,c,1,2)]=R.tile(1),R.tile(1)
    R.game_matches(g,m)
    R.game_apply(g,m)
    t:check(m.mask[target] and #m.special_effects==2,"matched line gem triggers bomb once")
    t:check(g.tiles[target].kind==-1,"the chain clears the bomb's neighbor")
end)
t:case("overlapping line and T prioritize color bomb",function()
    local R,g,m=fixture({"t_bomb","striped","color_bomb"})
    local c=R.hex_center()
    run(R,g,step(R,c,3,2),0,5)
    run(R,g,c,1,3)
    R.game_matches(g,m,c)
    t:check(m.hits==7,"crossing cells count only once")
    t:check(m.special_awards[c].name=="color_bomb" and next(m.special_awards,c)==nil,
        "priority yields one reward")
end)

-- The portrait campaigns play square cells: axis 0 is a row, axis 1 a column.
local function square()
    local R=E.new{square=true,columns=7,rows=7,colors=5,special_rules={"striped","color_bomb"}}
    return R,H.board(R),R.new_match()
end
local function fill(R,g,kind)
    for i=0,R.CELLS-1 do g.tiles[i]=R.tile(kind) end
end
t:case("square row of four leaves a line gem that clears its row",function()
    local R,g,m=square()
    local c=R.hex_center()
    run(R,g,step(R,c,3,2),0,4)
    g.tiles[c]=R.tile(2)
    local donor=R.hex_neighbor(c,1)
    g.tiles[donor]=R.tile(1)
    t:check(R.game_probe_swap(g,donor,c,m),"four in a row can be previewed")
    local award=m.special_awards and m.special_awards[c]
    t:check(award and award.name=="striped" and award.axis==0,"preview includes the line gem and its axis")
    t:check(R.game_swap(g,donor,c,m),"four in a row is a legal swap")
    R.game_apply(g,m)
    local gem=g.tiles[c]
    t:check(gem.special=="striped" and gem.kind==1 and gem.axis==0,"the gem keeps its color and the row axis")
    local edge=R.hex_index(-3,R.hex_r(c))
    g.tiles[edge]=R.tile(3)
    g.tiles[step(R,c,1,1)],g.tiles[step(R,c,1,2)]=R.tile(1),R.tile(1)
    R.game_matches(g,m)
    R.game_apply(g,m)
    t:check(m.mask[edge] and g.tiles[edge].kind==-1,"matching it sweeps the row to the edge")
    t:check(not m.ordinary[edge] and m.ordinary[c],"swept cells are hits, not matches")
end)
t:case("a sweep pays where a tool does not",function()
    local R,g,m=square()
    local c=R.hex_center()
    local edge=R.hex_index(-3,R.hex_r(c))
    g.match_only_resources,g.earnings=true,{0,0,0}
    g.resource_yields={[1]={slot=1,amount=1},[3]={slot=2,amount=1}}
    g.tiles[c],g.tiles[edge]=R.tile(1,"striped",0),R.tile(3)
    g.tiles[step(R,c,1,1)],g.tiles[step(R,c,1,2)]=R.tile(1),R.tile(1)
    R.game_matches(g,m)
    R.game_apply(g,m)
    t:check(g.earnings[1]==3 and g.earnings[2]==1,"matched and swept pieces are banked")
    g.tiles[edge]=R.tile(3)
    m=R.new_match()
    m.mask[edge],m.direct[edge]=true,true
    R.game_apply(g,m)
    t:check(g.earnings[2]==1,"a tool's direct hit still pays nothing")
end)
t:case("square column of five leaves a rainbow gem",function()
    local R,g,m=square()
    local c=R.hex_center()
    run(R,g,step(R,c,4,2),1,5)
    g.tiles[c]=R.tile(2)
    local donor=R.hex_neighbor(c,0)
    g.tiles[donor]=R.tile(1)
    t:check(R.game_swap(g,donor,c,m),"five in a column is a legal swap")
    R.game_apply(g,m)
    t:check(g.tiles[c].special=="color_bomb","five make a rainbow gem")
    local far,keep=R.hex_index(-3,-3),R.hex_index(3,3)
    g.tiles[donor],g.tiles[far],g.tiles[keep]=R.tile(3),R.tile(3),R.tile(4)
    t:check(R.game_swap(g,c,donor,m),"a rainbow gem fires on any swap")
    R.game_apply(g,m)
    t:check(g.tiles[far].kind==-1 and g.tiles[keep].kind==4,"it clears its partner's color only")
end)
t:case("two line gems cross",function()
    local R,g,m=square()
    fill(R,g,0)
    local c=R.hex_center()
    local a=R.hex_neighbor(c,0)
    g.tiles[c],g.tiles[a]=R.tile(1,"striped",0),R.tile(2,"striped",0)
    t:check(R.game_swap_matches(g,a,c),"two specials always swap")
    t:check(R.game_swap(g,a,c,m),"swap accepted")
    local row,column,off=R.hex_index(-3,R.hex_r(c)),R.hex_index(R.hex_q(c),-3),R.hex_index(-3,-3)
    t:check(m.mask[row] and m.mask[column] and not m.mask[off],"a row and a column through the moved gem")
    t:check(#m.special_effects==2,"one sweep per axis")
end)
t:case("bot aims a line-gem cross at its target",function()
    local R,g,m=square()
    local left,right=R.hex_index(0,0),R.hex_index(1,0)
    local target=R.hex_index(0,-3)
    g.tiles[left],g.tiles[right],g.tiles[target]=R.tile(1,"striped",0),R.tile(1,"striped",1),R.tile(2)
    g.oil[target],g.oil_left=1,1
    local a,b=require("greedy_bot")(R)(g)
    t:check(a==right and b==left,"bot reverses the swap to center the cross on the target column")
    t:check(R.game_swap(g,a,b,m) and m.mask[target],"the chosen cross actually hits the target")
end)
t:case("bot values a new rainbow gem",function()
    local R,g,m=square()
    local left,right=R.hex_index(0,-2),R.hex_index(1,-2)
    run(R,g,R.hex_index(0,-3),1,3)
    for y=-3,-1 do g.tiles[R.hex_index(1,y)]=R.tile(2) end
    g.tiles[left],g.tiles[right]=R.tile(2),R.tile(1)
    local gap,donor=R.hex_index(0,2),R.hex_index(0,3)
    run(R,g,R.hex_index(-2,2),0,5)
    g.tiles[gap],g.tiles[donor]=R.tile(2),R.tile(1)
    local legal,_,rainbow_score=R.game_probe_swap(g,donor,gap,m)
    local award=m.special_awards and m.special_awards[gap]
    t:check(legal and award and award.name=="color_bomb","preview includes the rainbow award")
    local ordinary,_,ordinary_score=R.game_probe_swap(g,left,right,m)
    t:check(ordinary and ordinary_score>rainbow_score and m.special_awards==nil,
        "two ordinary triples score more immediately and clear the previous award from the preview")
    local a,b=require("greedy_bot")(R)(g)
    t:check(R.game_swap(g,a,b,m) and m.special_awards and m.special_awards[gap]
        and m.special_awards[gap].name=="color_bomb","bot chooses to make the rainbow gem at equal goal progress")
end)
t:case("rainbow gem turns a line gem's color into line gems",function()
    local R,g,m=square()
    fill(R,g,0)
    local c=R.hex_center()
    local a=R.hex_neighbor(c,0)
    local far,other=R.hex_index(-3,-3),R.hex_index(3,3)
    g.tiles[c],g.tiles[a]=R.tile(1,"color_bomb"),R.tile(2,"striped",1)
    g.tiles[far],g.tiles[other]=R.tile(2),R.tile(3)
    t:check(R.game_swap(g,a,c,m),"swap accepted")
    t:check(g.tiles[far].special=="striped","the color becomes line gems")
    t:check(m.mask[far] and m.mask[R.hex_index(3,-3)],"each new gem sweeps its line")
    R.game_apply(g,m)
    t:check(g.tiles[other].kind==3 or m.mask[other],"other colors clear only when swept")
    t:check(g.tiles[far].kind==-1 and g.tiles[c].kind==-1,"the gems are consumed")
end)
t:case("two rainbow gems clear the board",function()
    local R,g,m=square()
    fill(R,g,0)
    local c=R.hex_center()
    local a=R.hex_neighbor(c,1)
    g.tiles[c],g.tiles[a]=R.tile(1,"color_bomb"),R.tile(2,"color_bomb")
    t:check(R.game_swap(g,a,c,m),"swap accepted")
    t:check(m.hits==R.CELLS,"every cell is hit")
end)
t:case("a chained line gem waits for its chain",function()
    local R,g,m=square()
    local c=R.hex_center()
    g.tiles[c]=R.tile(1,"striped",0)
    g.chain[c],g.obstacles=1,1
    local edge=R.hex_index(-3,R.hex_r(c))
    g.tiles[edge]=R.tile(3)
    g.tiles[step(R,c,1,1)],g.tiles[step(R,c,1,2)]=R.tile(1),R.tile(1)
    R.game_matches(g,m)
    R.game_apply(g,m)
    t:check(g.chain[c]==0 and g.tiles[c].special=="striped","the match breaks the chain and keeps the gem")
    t:check(g.tiles[edge].kind==3,"a locked gem does not sweep")
end)
t:case("the fast probe agrees with a matched line gem",function()
    local R,g=square()
    local c=R.hex_center()
    local edge=R.hex_index(-3,R.hex_r(c))
    g.tiles[c],g.tiles[edge]=R.tile(1,"striped",0),R.tile(3)
    g.oil[edge],g.oil_left=1,1
    g.tiles[step(R,c,1,1)]=R.tile(1)
    local third=step(R,c,1,2)
    local donor=R.hex_neighbor(third,0)
    g.tiles[third],g.tiles[donor]=R.tile(2),R.tile(1)
    local probe=R.new_match()
    local legal,progress=R.game_probe_swap(g,donor,third,probe)
    t:check(legal and progress==1,"the preview counts what the sweep clears")
end)
check(t:finish()==0)
